def test_reassignment_does_not_propagate_obsolete_model_or_payload() -> None:
    source = '''import requests
payload = {"model": "obsolete", "messages": [{"content": "Old instruction"}]}
payload = {"model": "current", "messages": [{"content": "New instruction"}]}
requests.post("https://private.example/infer", json=payload)
'''
    values = {item["value"] for item in extract_python_call_evidence(source)
              if item["type"] == "model_argument"}
    assert values == {"current"}


def test_structure_fingerprint_is_not_statistics_hash() -> None:
    source = "def f(x):\n    if x:\n        return x + 1\n    return 0\n"
    result = build_code_generation_signals(source, "python", "original_source", "a" * 64)
    fp = result["fingerprint"]
    assert fp["normalized_ast_hash"]
    assert fp["structure_stats_hash"]
    assert fp["normalized_ast_hash"] != fp["structure_stats_hash"]
    assert compare_fingerprints(fp, fp)["same_structure"] is True


def test_llm_prompt_enters_similarity_without_call_upgrade() -> None:
    features = {"prompt": {"embedded_prompts": []}, "toolchain": {"evidence": []}}
    LegacyAdapters._merge_semantic_facts(features, [{
        "signal_group": "prompt", "raw_value": "Summarize this record.",
        "prompt_role": "program_prompt", "source_unit_ids": ["unit:test"],
        "verification_status": "location_verified", "attribution_eligible": False,
    }])
    result = {"features": features}
    assert sample_profile(result)["prompt"]["records"]
    prompt = features["prompt"]["embedded_prompts"][0]
    assert prompt["comparison_eligible"] is True
    assert prompt["call_binding"] == "unverified"


def test_style_rejects_dialogue_in_embedded_prompt_and_batches_all_source() -> None:
    sha = "b" * 64
    source = b'''PROMPT = "Here's the code to summarize this record."
def one():
    return PROMPT
def two():
    # generated by AI for fixture
    return 2
'''
    index = build_material_index(source, {"sha256": sha, "language": "python", "source_encoding": "utf-8"})

    class Client:
        def __init__(self):
            self.calls = 0

        def analyze(self, units, *, task):
            self.calls += 1
            observations = []
            for unit in units:
                if "Here's the code" in unit["content"]:
                    observations.append({"label": "dialogue_residue", "raw_value": "Here's the code",
                                         "source_unit_ids": [unit["unit_id"]]})
                if "generated by AI" in unit["content"]:
                    observations.append({"label": "generation_claim", "raw_value": "generated by AI",
                                         "source_unit_ids": [unit["unit_id"]]})
            return {"observations": observations, "usage": {"total_tokens": 7}}

    client = Client()
    output = analyze_style(index, client, max_units=1)
    assert client.calls == len(index.units)
    assert output["source_units_considered"] == len(index.units)
    assert output["rejection_reasons"]["text_asset_not_code_style"] == 1
    assert [item["source_segment"] for item in output["observations"]] == ["comment"]
